<script lang="ts">
	import type { Note } from '$lib/types';
	import { invalidateAll } from '$app/navigation';
	import { formatDistanceToNow } from 'date-fns';
	import { ja } from 'date-fns/locale';
	import { createEventDispatcher } from 'svelte';
	import hljs from 'highlight.js';
	import { renderWikiLinks } from '$lib/utils/note-utils';
	import { protectNoteEmbeds, restoreNoteEmbeds } from '$lib/utils/note-embeds';
	import { sanitizeHtml, escapeHtml } from '$lib/utils/sanitize';
	import { customMarked } from '$lib/utils/markdown-renderer';
	import { offlineFetch } from '$lib/offline-queue';

	export let note: Note & { tags: string[] };
	export let mode: 'timeline' | 'archive' | 'trash' = 'timeline';
	export let compact = false; // リプライ（子メモ）表示用

	const dispatch = createEventDispatcher<{ edit: Note; delete: Note }>();

	// 埋め込み（![[...]]）を保護してからWikiLinkを解決し、最後にnote-embed:リンクとして復元
	$: noteEmbedsProtected = protectNoteEmbeds(note.content || '');
	$: processedContent = renderWikiLinks(noteEmbedsProtected.contentHtml, note.resolvedLinks);
	$: contentWithEmbeds = restoreNoteEmbeds(processedContent, noteEmbedsProtected.embeds);

	// Determine if the content is likely generated by Tiptap (already HTML)
	$: isHtmlContent = /<p>|<h[1-6]>|<ul|<ol|<blockquote|<pre|<div/i.test(contentWithEmbeds || '');

	function normalizeContentForStorage(text: string) {
		return text
			.replace(/\u00a0/g, ' ')
			.replace(/^[ \t]*&nbsp;[ \t]*$/gm, '')
			.replace(/&nbsp;/g, ' ');
	}

	// Action to manually apply enhancements (highlighting, copy buttons, interactive checkboxes)
	function enhanceProseContent(node: HTMLElement, _options?: unknown) {
		const applyEnhancements = () => {
			if (!node) return;
			node.querySelectorAll('pre').forEach((pre) => {
				if (!pre.parentElement?.classList.contains('code-block-wrapper')) {
					const wrapper = document.createElement('div');
					wrapper.className = 'code-block-wrapper';
					wrapper.style.position = 'relative';
					wrapper.style.margin = '1.5rem 0';
					pre.parentNode?.insertBefore(wrapper, pre);
					wrapper.appendChild(pre);
				}
			});

			node.querySelectorAll('.code-block-wrapper').forEach((wrapper) => {
				const block = wrapper.querySelector('pre code');
				if (block) {
					if (!block.classList.contains('hljs') && !block.hasAttribute('data-highlighted')) {
						hljs.highlightElement(block as HTMLElement);
						block.classList.add('hljs'); // Ensure the class is added just in case
					}

					// Add copy button if it doesn't exist
					if (!wrapper.querySelector('.copy-code-btn')) {
						wrapper.classList.add('group'); // For hover effect

						const button = document.createElement('button');
						button.className =
							'copy-code-btn btn btn-xs btn-square absolute right-2 top-2 opacity-0 transition-opacity z-10 bg-base-200/50 text-base-content hover:bg-base-300 border-none group-hover:opacity-100 backdrop-blur-sm';

						const copyIcon =
							'<svg xmlns="http://www.w3.org/2000/svg" width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><rect x="9" y="9" width="13" height="13" rx="2" ry="2"></rect><path d="M5 15H4a2 2 0 0 1-2-2V4a2 2 0 0 1 2-2h9a2 2 0 0 1 2 2v1"></path></svg>';
						const checkIcon =
							'<svg xmlns="http://www.w3.org/2000/svg" width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="text-success"><polyline points="20 6 9 17 4 12"></polyline></svg>';

						button.innerHTML = copyIcon;
						button.title = 'コードをコピー';

						button.onclick = async (e) => {
							e.stopPropagation();
							try {
								await navigator.clipboard.writeText(block.textContent || '');
								button.innerHTML = checkIcon;
								setTimeout(() => {
									if (button) button.innerHTML = copyIcon;
								}, 2000);
							} catch (err) {
								console.error('Failed to copy text: ', err);
							}
						};
						wrapper.appendChild(button);
					}
				}
			});

			// Attach change listeners to checkboxes
			node.querySelectorAll('input[type="checkbox"]').forEach((checkbox, index) => {
				const input = checkbox as HTMLInputElement;
				// Ensure we only attach once
				if (!input.hasAttribute('data-interactive-bound')) {
					input.setAttribute('data-interactive-bound', 'true');
					input.onchange = (e) => {
						e.stopPropagation();
						handleCheckboxChange(index, input.checked);
					};
					input.onclick = (e) => {
						e.stopPropagation();
					};
				}
			});

			// 埋め込み（note-embed:リンク）を本文に展開
			node.querySelectorAll('a[href^="note-embed:"]').forEach((anchor) => {
				const embedLink = anchor as HTMLAnchorElement;
				if (embedLink.hasAttribute('data-embed-bound')) return;
				embedLink.setAttribute('data-embed-bound', 'true');

				const href = embedLink.getAttribute('href') || '';
				const title = decodeURIComponent(href.replace('note-embed:', ''));
				const wrapper = document.createElement('div');
				wrapper.className =
					'note-embed-wrapper border-l-4 border-primary pl-4 py-2 my-4 bg-base-200/30 rounded-r-lg';
				wrapper.innerHTML = `
					<div class="text-xs text-base-content/50 mb-2 font-semibold flex items-center justify-between">
						<div class="flex items-center gap-1">
							<span>🔗</span>
							<span>埋め込み: ${escapeHtml(title)}</span>
						</div>
					</div>
					<div class="note-embed-content prose prose-sm max-w-none opacity-80">
						<span class="loading loading-dots loading-sm"></span>
					</div>
				`;

				const content = wrapper.querySelector('.note-embed-content') as HTMLElement | null;
				embedLink.replaceWith(wrapper);

				if (!content || !title) return;

				fetch(`/api/notes/embed?title=${encodeURIComponent(title)}`)
					.then((res) => {
						if (!res.ok) throw new Error('Not found');
						return res.json() as Promise<{ content?: string }>;
					})
					.then((data) => {
						const parsed = customMarked.parse(data.content || '', { breaks: true }) as string;
						content.innerHTML = sanitizeHtml(parsed);
					})
					.catch(() => {
						content.textContent = `ノート「${title}」が見つかりませんでした。`;
						content.className = 'text-error text-sm mt-2 block';
					});
			});
		};

		// Run initially after DOM settles
		setTimeout(applyEnhancements, 0);

		return {
			update() {
				setTimeout(applyEnhancements, 0);
			}
		};
	}

	async function handleCheckboxChange(index: number, isChecked: boolean) {
		if (!note.content) return;

		let newContent = note.content;

		if (isHtmlContent) {
			const parser = new DOMParser();
			const doc = parser.parseFromString(newContent, 'text/html');
			const checkboxes = doc.querySelectorAll('input[type="checkbox"]');

			if (checkboxes[index]) {
				const checkbox = checkboxes[index] as HTMLInputElement;
				if (isChecked) {
					checkbox.setAttribute('checked', 'checked');
				} else {
					checkbox.removeAttribute('checked');
				}

				const li = checkbox.closest('li[data-type="taskItem"]');
				if (li) {
					li.setAttribute('data-checked', isChecked ? 'true' : 'false');
				}
				newContent = doc.body.innerHTML;
			}
		} else {
			// Markdown approach
			let matchCount = 0;
			// Match a markdown list item with checkbox like "- [ ] " or "* [x] "
			newContent = newContent.replace(/^(\s*[-*+]\s+)\[([ xX])\]/gm, (match, prefix) => {
				if (matchCount === index) {
					matchCount++;
					return `${prefix}[${isChecked ? 'x' : ' '}]`;
				}
				matchCount++;
				return match;
			});
		}

		if (newContent !== note.content) {
			newContent = normalizeContentForStorage(newContent);

			const oldContent = note.content;
			note.content = newContent; // Optimistic update
			try {
				const response = await offlineFetch(`/api/notes/${note.id}`, {
					method: 'PUT',
					headers: { 'Content-Type': 'application/json' },
					body: JSON.stringify({ content: newContent })
				});
				if ('queued' in response) {
					// オフライン: キューに保存（楽観的更新のまま。復帰後に自動再送）
					return;
				}
				if (!response.ok) {
					console.error('Failed to update check status');
					note.content = oldContent; // Revert on failure
				} else {
					// Refresh list so other UI parts (like note view) show the right state
					await invalidateAll();
				}
			} catch (e) {
				console.error('Error updating checkbox', e);
				note.content = oldContent; // Revert on failure
			}
		}
	}

	let interactionDebounce = false;
	function handleInteraction() {
		if (interactionDebounce) return;
		interactionDebounce = true;

		console.log('Edit event dispatched for note:', note);
		dispatch('edit', note);

		setTimeout(() => {
			interactionDebounce = false;
		}, 300);
	}

	let element: HTMLElement;
	let deleteDialog: HTMLDialogElement;
	let touchStartX = 0;
	let touchStartY = 0;
	let touchCurrentX = 0;
	let isSwiping = false;
	const swipeThreshold = 100; // Swipe distance in pixels to trigger action

	function handleTouchStart(e: TouchEvent) {
		if (compact) {
			isSwiping = false;
			return;
		}
		// Don't start swipe if touching an interactive element
		const target = e.target as HTMLElement;
		if (target.closest('button, input, a, [role="button"]')) {
			isSwiping = false;
			return;
		}

		touchStartX = e.touches[0].clientX;
		touchStartY = e.touches[0].clientY; // Track Y for scroll detection
		touchCurrentX = touchStartX;
		isSwiping = true;
	}

	function handleTouchMove(e: TouchEvent) {
		if (!isSwiping) return;
		touchCurrentX = e.touches[0].clientX;
		const touchCurrentY = e.touches[0].clientY;

		const diffX = touchCurrentX - touchStartX;
		const diffY = touchCurrentY - touchStartY;

		// If user is scrolling vertically more than horizontally, cancel swipe
		if (Math.abs(diffY) > Math.abs(diffX) && Math.abs(diffY) > 10) {
			isSwiping = false;
			element.style.transform = 'translateX(0)';
			return;
		}

		// Prevent default only if we are horizontally swiping to avoid blocking scroll
		if (Math.abs(diffX) > 10) {
			// e.preventDefault(); // Might cause issues in some browsers
			element.style.transform = `translateX(${diffX}px)`;
		}
	}

	function handleTouchEnd() {
		if (!isSwiping) return;
		const diff = touchCurrentX - touchStartX;

		// Reset style
		element.style.transform = 'translateX(0)';
		isSwiping = false;

		if (mode === 'timeline') {
			if (diff > swipeThreshold) {
				// Right swipe
				sendToBox();
			} else if (diff < -swipeThreshold) {
				// Left swipe
				sendToArchive();
			}
		}

		touchStartX = 0;
		touchCurrentX = 0;
	}

	async function updateNoteStatus(status: 'inbox' | 'box' | 'archived' | 'trash') {
		try {
			const response = await fetch(`/api/notes/${note.id}/status`, {
				method: 'POST',
				headers: { 'Content-Type': 'application/json' },
				body: JSON.stringify({ status })
			});
			if (response.ok) {
				await invalidateAll();
			} else {
				console.error(`Failed to move note to ${status}`);
			}
		} catch (error) {
			console.error('Error updating note status:', error);
		}
	}

	async function togglePin() {
		try {
			const response = await fetch(`/api/notes/${note.id}/pin`, {
				method: 'POST'
			});
			if (response.ok) {
				await invalidateAll();
			} else {
				console.error('Failed to toggle pin');
			}
		} catch (error) {
			console.error('Error toggling pin:', error);
		}
	}

	function openDeleteModal() {
		if (deleteDialog) {
			deleteDialog.showModal();
		}
	}

	async function deletePermanently() {
		try {
			const response = await fetch(`/api/notes/${note.id}`, {
				method: 'DELETE'
			});
			if (response.ok) {
				if (deleteDialog) deleteDialog.close();
				dispatch('delete', note);
				await invalidateAll();
			} else {
				console.error('Failed to delete note permanently');
			}
		} catch (error) {
			console.error('Error deleting note permanently:', error);
		}
	}

	// リプライ（親メモへのぶら下げ）
	let showReplyForm = false;
	let replyText = '';
	let isSubmittingReply = false;

	async function submitReply() {
		const content = replyText.trim();
		if (!content || isSubmittingReply) return;
		isSubmittingReply = true;
		try {
			const response = await fetch('/api/notes', {
				method: 'POST',
				headers: { 'Content-Type': 'application/json' },
				body: JSON.stringify({ title: '', content, parentId: note.id })
			});
			if (response.ok) {
				replyText = '';
				showReplyForm = false;
				await invalidateAll();
			} else {
				console.error('Failed to create reply:', await response.text());
			}
		} catch (error) {
			console.error('Error creating reply:', error);
		} finally {
			isSubmittingReply = false;
		}
	}

	const sendToBox = () => updateNoteStatus('box');
	const sendToArchive = () => updateNoteStatus('archived');
	const sendToTrash = () => updateNoteStatus('trash');
	const restoreToInbox = () => updateNoteStatus('inbox');

	// 操作アイコン（Material Icons）
	const ICON = {
		edit: 'M3 17.25V21h3.75L17.81 9.94l-3.75-3.75L3 17.25zM20.71 7.04c.39-.39.39-1.02 0-1.41l-2.34-2.34c-.39-.39-1.02-.39-1.41 0l-1.83 1.83 3.75 3.75 1.83-1.83z',
		reply:
			'M20 2H4c-1.1 0-2 .9-2 2v18l4-4h14c1.1 0 2-.9 2-2V4c0-1.1-.9-2-2-2zm0 14H6l-2 2V4h16v12z',
		pin: 'M16 12V4h1V2H7v2h1v8l-2 2v2h5.2v6h1.6v-6H18v-2l-2-2z',
		box: 'M20 2H4c-1 0-2 .9-2 2v3.01c0 .72.43 1.34 1 1.69V20c0 1.1 1.1 2 2 2h14c.9 0 2-.9 2-2V8.7c.57-.35 1-.97 1-1.69V4c0-1.1-1-2-2-2zm-5 12H9v-2h6v2zm5-7H4V4h16v3z',
		archive:
			'M20.54 5.23l-1.39-1.68C18.88 3.21 18.47 3 18 3H6c-.47 0-.88.21-1.16.55L3.46 5.23C3.17 5.57 3 6.02 3 6.5V19c0 1.1.9 2 2 2h14c1.1 0 2-.9 2-2V6.5c0-.48-.17-.93-.46-1.27zM12 17.5L6.5 12H10v-2h4v2h3.5L12 17.5zM5.12 5l.81-1h12l.94 1H5.12z',
		restore:
			'M20.55 5.22l-1.39-1.68C18.88 3.21 18.47 3 18 3H6c-.47 0-.88.21-1.15.55L3.46 5.22C3.17 5.57 3 6.01 3 6.5V19c0 1.1.9 2 2 2h14c1.1 0 2-.9 2-2V6.5c0-.49-.17-.93-.45-1.28zM12 9.5l5.5 5.5H14v2h-4v-2H6.5L12 9.5zM5.12 5l.82-1h12l.93 1H5.12z',
		trash:
			'M6 19c0 1.1.9 2 2 2h8c1.1 0 2-.9 2-2V7H6v12zM19 4h-3.5l-1-1h-5l-1 1H5v2h14V4z'
	};

	const formattedDate = formatDistanceToNow(new Date(note.updatedAt), {
		addSuffix: true,
		locale: ja
	});
</script>

<div
	bind:this={element}
	class="card transition-transform duration-200 ease-in-out select-none {compact
		? 'border-base-200 bg-base-100/70 border shadow-none'
		: 'bg-base-100 shadow-md'}"
	ontouchstart={handleTouchStart}
	ontouchmove={handleTouchMove}
	ontouchend={handleTouchEnd}
	role="article"
	aria-label={note.title || 'メモ'}
>
	<div class="card-body p-4">
		{#if note.isPinned}
			<div class="text-primary absolute top-2 right-2">
				<svg
					xmlns="http://www.w3.org/2000/svg"
					class="h-5 w-5"
					viewBox="0 0 20 20"
					fill="currentColor"
				>
					<path
						d="M16 12V4a2 2 0 00-2-2h-4a2 2 0 00-2 2v8l-2 2v2h5.2v5l1.8 2 1.8-2v-5H18v-2l-2-2z"
					/>
				</svg>
			</div>
		{/if}

		{#if note.title && note.title !== 'Untitled Note'}
			<h2 class="mb-2 text-xl font-bold">{note.title}</h2>
		{/if}

		<div class="prose text-base-content max-w-none" use:enhanceProseContent={contentWithEmbeds}>
			{#if isHtmlContent}
				<!-- eslint-disable-next-line svelte/no-at-html-tags -->
				{@html sanitizeHtml(contentWithEmbeds || '')}
			{:else}
				<!-- eslint-disable-next-line svelte/no-at-html-tags -->
				{@html sanitizeHtml(customMarked.parse(contentWithEmbeds || '', { breaks: true }) as string)}
			{/if}
		</div>

		<div class="text-base-content/60 mt-4 flex items-center justify-between text-xs">
			<span>{formattedDate}</span>
			<div class="card-actions items-center gap-0.5">
				{#if !compact}
					<button
						class="btn btn-ghost btn-sm btn-square"
						title="編集"
						aria-label="編集"
						onclick={handleInteraction}
					>
						<svg xmlns="http://www.w3.org/2000/svg" height="16" viewBox="0 0 24 24" width="16" fill="currentColor"><path d={ICON.edit} /></svg>
					</button>
				{/if}
				{#if mode === 'timeline' && !compact}
					<button
						class="btn btn-ghost btn-sm btn-square"
						title="返信"
						aria-label="返信"
						onclick={(e) => {
							e.stopPropagation();
							showReplyForm = !showReplyForm;
						}}
					>
						<svg xmlns="http://www.w3.org/2000/svg" height="16" viewBox="0 0 24 24" width="16" fill="currentColor"><path d={ICON.reply} /></svg>
					</button>
					<button
						class="btn btn-ghost btn-sm btn-square {note.isPinned ? 'text-primary' : ''}"
						title={note.isPinned ? 'ピンを外す' : 'ピン'}
						aria-label={note.isPinned ? 'ピンを外す' : 'ピン'}
						onclick={(e) => {
							e.stopPropagation();
							togglePin();
						}}
					>
						<svg xmlns="http://www.w3.org/2000/svg" height="16" viewBox="0 0 24 24" width="16" fill="currentColor"><path d={ICON.pin} /></svg>
					</button>
					<button
						class="btn btn-ghost btn-sm btn-square"
						title="Boxへ移動"
						aria-label="Boxへ移動"
						onclick={(e) => {
							e.stopPropagation();
							sendToBox();
						}}
					>
						<svg xmlns="http://www.w3.org/2000/svg" height="16" viewBox="0 0 24 24" width="16" fill="currentColor"><path d={ICON.box} /></svg>
					</button>
					<button
						class="btn btn-ghost btn-sm btn-square"
						title="アーカイブ"
						aria-label="アーカイブ"
						onclick={(e) => {
							e.stopPropagation();
							sendToArchive();
						}}
					>
						<svg xmlns="http://www.w3.org/2000/svg" height="16" viewBox="0 0 24 24" width="16" fill="currentColor"><path d={ICON.archive} /></svg>
					</button>
				{:else if mode === 'archive'}
					<button
						class="btn btn-ghost btn-sm btn-square"
						title="受信箱に戻す"
						aria-label="受信箱に戻す"
						onclick={(e) => {
							e.stopPropagation();
							restoreToInbox();
						}}
					>
						<svg xmlns="http://www.w3.org/2000/svg" height="16" viewBox="0 0 24 24" width="16" fill="currentColor"><path d={ICON.restore} /></svg>
					</button>
					<button
						class="btn btn-ghost btn-sm btn-square text-error"
						title="ゴミ箱へ"
						aria-label="ゴミ箱へ"
						onclick={(e) => {
							e.stopPropagation();
							sendToTrash();
						}}
					>
						<svg xmlns="http://www.w3.org/2000/svg" height="16" viewBox="0 0 24 24" width="16" fill="currentColor"><path d={ICON.trash} /></svg>
					</button>
				{:else if mode === 'trash'}
					<button
						class="btn btn-ghost btn-sm btn-square"
						title="受信箱に戻す"
						aria-label="受信箱に戻す"
						onclick={(e) => {
							e.stopPropagation();
							restoreToInbox();
						}}
					>
						<svg xmlns="http://www.w3.org/2000/svg" height="16" viewBox="0 0 24 24" width="16" fill="currentColor"><path d={ICON.restore} /></svg>
					</button>
					<button
						class="btn btn-ghost btn-sm btn-square text-error"
						title="完全に削除"
						aria-label="完全に削除"
						onclick={(e) => {
							e.stopPropagation();
							openDeleteModal();
						}}
					>
						<svg xmlns="http://www.w3.org/2000/svg" height="16" viewBox="0 0 24 24" width="16" fill="currentColor"><path d={ICON.trash} /></svg>
					</button>
				{/if}
			</div>
		</div>

		{#if showReplyForm && !compact}
			<div class="border-base-300 mt-3 border-t pt-3">
				<textarea
					class="textarea textarea-bordered w-full text-sm"
					rows="2"
					placeholder="返信を書く..."
					bind:value={replyText}
					onclick={(e) => e.stopPropagation()}
				></textarea>
				<div class="mt-2 flex justify-end gap-2">
					<button
						class="btn btn-ghost btn-xs"
						onclick={(e) => {
							e.stopPropagation();
							showReplyForm = false;
						}}
					>
						キャンセル
					</button>
					<button
						class="btn btn-primary btn-xs"
						onclick={(e) => {
							e.stopPropagation();
							submitReply();
						}}
						disabled={isSubmittingReply || !replyText.trim()}
					>
						{isSubmittingReply ? '送信中...' : '返信'}
					</button>
				</div>
			</div>
		{/if}
	</div>
</div>

<!-- 削除確認モーダル -->
